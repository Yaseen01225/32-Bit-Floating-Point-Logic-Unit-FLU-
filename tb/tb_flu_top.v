`timescale 1ns / 1ps
// Defines the simulation time unit as 1 nanosecond.
// Defines the simulation time precision as 1 picosecond.
// For example, #10 represents a delay of 10 nanoseconds.

// ============================================================================
// Project   : Floating-Point Logic Unit (FLU)
// File      : tb_flu_top.v
// Developer : Ghulam Yaseen Nangraj
// Date      : 2026-10-16
// Platform  : Xilinx Vivado v2025.2.1
//
// Purpose:
//   This testbench verifies the functionality of a combinational floating-
//   point logic unit by supplying decimal operands and checking the results.
//
// Operation Codes:
//   000 = Addition
//   001 = Subtraction
//   010 = Multiplication
//   011 = Division
//   100 = Square
//   101 = Square Root
//
// Important Notes:
//   - This is a testbench, not synthesizable hardware.
//   - No clock or reset signal is required.
//   - fp32_encode converts decimal input fields to IEEE-754 single precision.
//   - flu_top performs the selected floating-point operation.
//   - A short delay is inserted after input changes to allow combinational
//     logic to settle before checking the result.
//   - The expected results are specified as 32-bit hexadecimal IEEE-754 values.
// ============================================================================


// Declares the testbench module.
// A testbench is the simulation environment used to verify the design.
// It does not have input or output ports because it drives and observes
// the modules instantiated inside it.
module tb_flu_top;

    // ========================================================================
    // SECTION 1: DECLARATION OF INPUT SIGNALS FOR OPERAND A
    // ========================================================================

    // Sign bit for operand A.
    // 1'b0 represents a positive number.
    // 1'b1 represents a negative number.
    reg sign_a;

    // Integer (whole-number) part of operand A.
    // The 32-bit unsigned field can represent decimal integer input values.
    reg [31:0] whole_a;

    // Numerator-like field containing the fractional digits.
    // Example: fraction_a = 5 and fractional_digits_a = 1 represent 0.5.
    // Example: fraction_a = 127 and fractional_digits_a = 3 represent 0.127.
    reg [31:0] fraction_a;

    // Number of decimal places in fraction_a.
    // The encoder uses this field to determine the fractional scale.
    // Example: 4'd1 means divide fraction_a by 10.
    //          4'd3 means divide fraction_a by 1000.
    reg [3:0] fractional_digits_a;


    // ========================================================================
    // SECTION 2: DECLARATION OF INPUT SIGNALS FOR OPERAND B
    // ========================================================================

    // Sign bit for operand B.
    // 0 means positive, and 1 means negative.
    reg sign_b;

    // Integer part of operand B.
    reg [31:0] whole_b;

    // Fractional digits of operand B.
    reg [31:0] fraction_b;

    // Number of decimal places used to interpret fraction_b.
    reg [3:0] fractional_digits_b;


    // ========================================================================
    // SECTION 3: ENCODED OPERANDS AND FLU OUTPUT SIGNALS
    // ========================================================================

    // IEEE-754 single-precision representation of operand A.
    // A 32-bit floating-point value contains:
    //   Bit 31     : Sign
    //   Bits 30:23 : Biased exponent
    //   Bits 22:0  : Fraction (significand field)
    //
    // This signal is driven by the fp32_encode module.
    // A wire is used because the value is generated by another module.
    wire [31:0] operand_a;

    // IEEE-754 single-precision representation of operand B.
    // This signal is driven by the second fp32_encode module.
    wire [31:0] operand_b;

    // Selects which arithmetic operation the FLU should perform.
    // The 3-bit value is interpreted according to the operation codes
    // implemented in flu_top.
    reg [2:0] operation;

    // Receives the 32-bit IEEE-754 result from the FLU.
    wire [31:0] result;

    // Indicates whether the selected division operation encountered
    // a zero divisor.
    // Expected to be 1 during division by zero and 0 during normal division.
    wire divide_by_zero;


    // ========================================================================
    // SECTION 4: INSTANTIATION OF THE FIRST DECIMAL-TO-FLOAT ENCODER
    // ========================================================================

    // Creates an instance named encode_a of the fp32_encode module.
    // This module converts the decimal fields for operand A into IEEE-754.
    fp32_encode encode_a (

        // Supplies the sign bit to the encoder.
        .sign(sign_a),

        // Supplies the integer part of operand A.
        .whole(whole_a),

        // Supplies the fractional digits of operand A.
        .fraction(fraction_a),

        // Supplies the number of decimal places.
        .fractional_digits(fractional_digits_a),

        // Receives the resulting 32-bit floating-point representation.
        .result(operand_a)
    );


    // ========================================================================
    // SECTION 5: INSTANTIATION OF THE SECOND DECIMAL-TO-FLOAT ENCODER
    // ========================================================================

    // Creates another fp32_encode instance named encode_b.
    // It performs the same conversion for operand B.
    // Both encoders operate independently on their respective inputs.
    fp32_encode encode_b (

        // Supplies the sign bit for operand B.
        .sign(sign_b),

        // Supplies the integer part of operand B.
        .whole(whole_b),

        // Supplies the fractional digits of operand B.
        .fraction(fraction_b),

        // Supplies the number of decimal places for operand B.
        .fractional_digits(fractional_digits_b),

        // Receives the IEEE-754 representation of operand B.
        .result(operand_b)
    );


    // ========================================================================
    // SECTION 6: INSTANTIATION OF THE DEVICE UNDER TEST (DUT)
    // ========================================================================

    // Creates an instance of the top-level floating-point logic unit.
    // The instance name "dut" means Device Under Test.
    // This is the hardware module whose behavior is being verified.
    flu_top dut (

        // Supplies encoded operand A to the FLU.
        .operand_a(operand_a),

        // Supplies encoded operand B to the FLU.
        .operand_b(operand_b),

        // Selects the arithmetic operation.
        .operation(operation),

        // Receives the floating-point result.
        .result(result),

        // Receives the division-by-zero status flag.
        .divide_by_zero(divide_by_zero)
    );


    // ========================================================================
    // SECTION 7: TASK FOR CHECKING AND REPORTING TEST RESULTS
    // ========================================================================

    // Declares a reusable task named check_result.
    // A task groups statements that can be called multiple times.
    // This avoids repeating the same result-printing and comparison code.
    task check_result;

        // First argument: descriptive name of the test.
        // 8*48 bits provide storage for 48 ASCII characters.
        input [8*48-1:0] test_name;

        // Second argument: expected 32-bit IEEE-754 result.
        input [31:0] expected;

        // Begins the executable portion of the task.
        begin

            // Prints the simulation time, test name, operation code,
            // both encoded operands, actual result, expected result,
            // and division-by-zero status.
            //
            // %0t : simulation time without unnecessary padding.
            // %0s : test name as a string.
            // %b  : binary representation.
            // %h  : hexadecimal representation.
            // %0d : not used here; %0t is used for time.
            $display(
                "%0t | %0s | OP=%b | A=%h | B=%h | RESULT=%h | EXPECTED=%h | DIV0=%b",
                $time,              // Current simulation time.
                test_name,          // Name of the current test.
                operation,          // Selected operation code.
                operand_a,          // Encoded first operand.
                operand_b,          // Encoded second operand.
                result,             // Actual result from the FLU.
                expected,           // Expected IEEE-754 result.
                divide_by_zero      // Division-by-zero status.
            );

            // Uses case inequality ( !== ) to compare the actual and
            // expected results bit by bit.
            // Unlike ordinary inequality, case inequality also detects
            // unknown (X) and high-impedance (Z) bits.
            if (result !== expected)

                // Reports an error if any result bit differs.
                $display("  ERROR: Result mismatch in %0s", test_name);

            else

                // Reports a successful comparison.
                $display("  PASS: %0s", test_name);

        // Ends the task's executable block.
        end

    // Ends the task definition.
    endtask


    // ========================================================================
    // SECTION 8: INITIAL BLOCK AND TEST SEQUENCE
    // ========================================================================

    // An initial block executes once when simulation begins.
    // It applies test vectors sequentially, checks the outputs,
    // prints diagnostic messages, and terminates the simulation.
    initial begin

        // Prints a separator to make the simulation log easier to read.
        $display("==========================================================================");

        // Prints the testbench title.
        $display("          COMBINATIONAL FLU TESTBENCH - DECIMAL INPUTS");

        // Prints another separator.
        $display("==========================================================================");

        // Prints the column headings for the test output.
        $display("Time | Test | OP | Operand A | Operand B | Result | Expected | DIV0");


        // ====================================================================
        // SECTION 9: INITIALIZE ALL INPUTS
        // ====================================================================

        // Initialize operand A's sign to positive.
        sign_a = 1'b0;

        // Initialize operand A's integer part to zero.
        whole_a = 32'd0;

        // Initialize operand A's fractional digits to zero.
        fraction_a = 32'd0;

        // Specify zero decimal places for operand A.
        fractional_digits_a = 4'd0;


        // Initialize operand B's sign to positive.
        sign_b = 1'b0;

        // Initialize operand B's integer part to zero.
        whole_b = 32'd0;

        // Initialize operand B's fractional digits to zero.
        fraction_b = 32'd0;

        // Specify zero decimal places for operand B.
        fractional_digits_b = 4'd0;


        // Select addition as the initial operation.
        operation = 3'b000;

        // Wait 10 ns for the encoder and FLU combinational logic to settle.
        #10;


        // ====================================================================
        // TEST 1: ADDITION
        // Mathematical operation: 1.5 + 2.0 = 3.5
        // Expected IEEE-754 result: 32'h40600000
        // ====================================================================

        // Configure operand A as a positive number.
        sign_a = 1'b0;

        // Set the integer part of A to 1.
        whole_a = 32'd1;

        // Set the fractional digits to 5.
        fraction_a = 32'd5;

        // One fractional digit means 5 / 10 = 0.5.
        fractional_digits_a = 4'd1;


        // Configure operand B as positive.
        sign_b = 1'b0;

        // Set the integer part of B to 2.
        whole_b = 32'd2;

        // Set the fractional part to zero.
        fraction_b = 32'd0;

        // Zero fractional digits indicate an integer input.
        fractional_digits_b = 4'd0;


        // Select addition: 3'b000.
        operation = 3'b000;

        // Allow 10 ns for the new inputs to propagate through the design.
        #10;

        // Compare the result with the IEEE-754 encoding of 3.5.
        check_result("Addition: 1.5 + 2.0", 32'h40600000);


        // ====================================================================
        // TEST 2: SUBTRACTION
        // Mathematical operation: 2.0 - 1.5 = 0.5
        // Expected IEEE-754 result: 32'h3F000000
        // ====================================================================

        // Change operand A's integer part to 2.
        whole_a = 32'd2;

        // Set operand A's fractional part to zero.
        fraction_a = 32'd0;

        // Specify no fractional decimal places.
        fractional_digits_a = 4'd0;


        // Change operand B's integer part to 1.
        whole_b = 32'd1;

        // Set operand B's fractional digits to 5.
        fraction_b = 32'd5;

        // Interpret the fractional part as 5 / 10 = 0.5.
        fractional_digits_b = 4'd1;


        // Select subtraction: 3'b001.
        operation = 3'b001;

        // Wait for the combinational result to settle.
        #10;

        // Verify that 2.0 - 1.5 produces 0.5.
        check_result("Subtraction: 2.0 - 1.5", 32'h3F000000);


        // ====================================================================
        // TEST 3: MULTIPLICATION
        // Mathematical operation: 1.5 * 2.0 = 3.0
        // Expected IEEE-754 result: 32'h40400000
        // ====================================================================

        // Configure operand A as 1.5.
        whole_a = 32'd1;
        fraction_a = 32'd5;
        fractional_digits_a = 4'd1;

        // Configure operand B as 2.0.
        whole_b = 32'd2;
        fraction_b = 32'd0;
        fractional_digits_b = 4'd0;


        // Select multiplication: 3'b010.
        operation = 3'b010;

        // Wait for the multiplication result.
        #10;

        // Verify that the result equals the IEEE-754 representation of 3.0.
        check_result("Multiplication: 1.5 * 2.0", 32'h40400000);


        // ====================================================================
        // TEST 4: DIVISION
        // Mathematical operation: 1.5 / 2.0 = 0.75
        // Expected IEEE-754 result: 32'h3F400000
        // ====================================================================

        // Operand A remains 1.5 from the previous test.
        // Operand B remains 2.0 from the previous test.

        // Select division: 3'b011.
        operation = 3'b011;

        // Wait for the division result and status flag to settle.
        #10;

        // Verify that 1.5 / 2.0 produces 0.75.
        check_result("Division: 1.5 / 2.0", 32'h3F400000);


        // Verify that division by a nonzero value does not assert DIV0.
        // Case inequality also detects an unknown X status.
        if (divide_by_zero !== 1'b0)

            // Report an error if the status is not definitely zero.
            $display("  ERROR: DIV0 should be 0 for a nonzero divisor");


        // ====================================================================
        // TEST 5: DIVISION BY ZERO
        // Mathematical operation: 1.5 / 0.0
        // Expected status: divide_by_zero = 1
        // The result bit pattern depends on the implementation of fp32_div.
        // ====================================================================

        // Set operand B's integer part to zero.
        whole_b = 32'd0;

        // Set operand B's fractional part to zero.
        fraction_b = 32'd0;

        // Specify no fractional decimal places.
        fractional_digits_b = 4'd0;


        // Keep the operation set to division.
        operation = 3'b011;

        // Allow the encoder and divider to update their outputs.
        #10;


        // Print the division-by-zero test details.
        // This display does not compare the numerical result because the
        // divider's special-case result has not been specified here.
        $display(
            "%0t | Division by zero | OP=%b | A=%h | B=%h | RESULT=%h | DIV0=%b",
            $time,              // Current simulation time.
            operation,          // Current operation code.
            operand_a,          // Encoded dividend.
            operand_b,          // Encoded zero divisor.
            result,             // Divider's special-case result.
            divide_by_zero      // Expected to be asserted.
        );


        // Verify that the divider asserts the division-by-zero flag.
        if (divide_by_zero !== 1'b1)

            // Report an error if the flag is zero or unknown.
            $display("  ERROR: DIV0 should be 1");

        else

            // Report success when the flag is definitely one.
            $display("  PASS: Division-by-zero flag asserted");


        // ====================================================================
        // TEST 6: SQUARE
        // Mathematical operation: (1.5)^2 = 2.25
        // Expected IEEE-754 result: 32'h40100000
        // ====================================================================

        // Configure operand A as 1.5.
        whole_a = 32'd1;
        fraction_a = 32'd5;
        fractional_digits_a = 4'd1;

        // Select square: 3'b100.
        // The implementation of flu_top must recognize this operation code.
        operation = 3'b100;

        // Wait for the square result to settle.
        #10;

        // Verify that squaring 1.5 produces 2.25.
        check_result("Square: 1.5 squared", 32'h40100000);


        // ====================================================================
        // TEST 7: SQUARE ROOT
        // Mathematical operation: sqrt(1.5) approximately equals 1.224744870
        // Expected IEEE-754 result: 32'h3F9CC470
        // ====================================================================

        // Set operand A's integer part to 1.
        whole_a = 32'd1;

        // Set operand A's fractional digits to 5.
        fraction_a = 32'd5;

        // Interpret the fractional part as 5 / 10 = 0.5.
        fractional_digits_a = 4'd1;


        // Select square root: 3'b101.
        // This code must match the square-root operation implemented in flu_top.
        operation = 3'b101;

        // Wait for the square-root result to settle.
        #10;

        // Compare the square-root output against the expected IEEE-754 value.
        check_result("Square Root: sqrt(1.5)", 32'h3F9CC471);


        // ====================================================================
        // TEST 8: SIGNED CANCELLATION
        // Mathematical operation: +23.127 + (-23.127) = +0.0
        // Expected IEEE-754 result: 32'h00000000
        // ====================================================================

        // Set operand A to a positive number.
        sign_a = 1'b0;

        // Set the integer part of operand A to 23.
        whole_a = 32'd23;

        // Set the fractional digits to 127.
        fraction_a = 32'd127;

        // Three fractional digits mean 127 / 1000 = 0.127.
        fractional_digits_a = 4'd3;


        // Set operand B to a negative number.
        sign_b = 1'b1;

        // Set the integer part of operand B to 23.
        whole_b = 32'd23;

        // Set the fractional digits to 127.
        fraction_b = 32'd127;

        // Three fractional digits mean 127 / 1000 = 0.127.
        fractional_digits_b = 4'd3;


        // Select addition to test cancellation of opposite-signed operands.
        operation = 3'b000;

        // Wait for both encoders and the adder to settle.
        #10;


        // Display the encoded IEEE-754 bit pattern for positive 23.127.
        // This helps verify the decimal-to-floating-point encoder.
        $display("Encoder +23.127 = %h", operand_a);

        // Display the encoded IEEE-754 bit pattern for negative 23.127.
        $display("Encoder -23.127 = %h", operand_b);

        // Verify that adding equal and opposite operands produces positive zero.
        check_result("Cancellation: 23.127 + (-23.127)", 32'h00000000);


        // ====================================================================
        // SECTION 10: END OF SIMULATION
        // ====================================================================

        // Print a separator before the final status message.
        $display("==========================================================================");

        // Inform the user that all scheduled test vectors have been executed.
        // Review the simulator transcript for ERROR messages.
        $display("Combinational FLU testbench finished. Review any ERROR messages above.");

        // Print the final separator.
        $display("==========================================================================");

        // Stop the simulation.
        // No further statements in this initial block will execute.
        $finish;

    // Ends the initial block.
    end

// Ends the testbench module.
endmodule